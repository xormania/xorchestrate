"""Render the committed example file from the declared table, so the two cannot drift."""

from __future__ import annotations

from collections.abc import Iterable

from scripts.devconfig.model import Setting

HEADER = (
    "# Optional developer settings for this repository's dev tools. Nothing requires this file.",
    "# Copy it to .devtools.env in the main checkout (git-ignored), remove the # from a setting and",
    "# write its value; or set the same names in the environment or in devtools.env under the XDG",
    "# config directory. Precedence: flags, environment, .devtools.env, user file, defaults.",
    "# Never put secrets here. Plain KEY=VALUE lines; values are literal text, never executed.",
    "# Generated by `python3 -m scripts.devconfig example --write`; do not edit by hand.",
)


def render_example(settings: Iterable[Setting]) -> str:
    lines = list(HEADER)
    section = None
    for setting in settings:
        if setting.section != section:
            section = setting.section
            lines += ["", f"# [{section}]"]
        lines += ["", f"# {setting.description}"]
        if setting.default is not None:
            lines.append(f"#   default: {setting.default}")
        lines.append(f"# {setting.key}=")
    return "\n".join(lines) + "\n"
